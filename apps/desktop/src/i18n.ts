import { writable } from "svelte/store";

export type UiLanguage = "zh-CN" | "en";
const STORAGE_KEY = "nmixx.ui.language";

/** The UI defaults to Chinese. Never derive the product language from OS locale. */
export const uiLanguage = writable<UiLanguage>("zh-CN");

export function restoreUiLanguage(): void {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "zh-CN") uiLanguage.set(saved);
  } catch { /* Private/unsupported storage: retain Chinese default. */ }
}

export function setUiLanguage(language: UiLanguage): void {
  uiLanguage.set(language);
  try { localStorage.setItem(STORAGE_KEY, language); }
  catch { /* Language still switches for the current session. */ }
}

